// Regenerates site/src/lib/audit/seatPrices.ts from the newest shipped rate sheet
// (src/config/pricing-*.json). The site cannot import ../src at build time — Vercel uploads
// only site/ — so the audit carries a generated mirror, and seatPrices.test.js fails the
// suite if the mirror and the sheet ever disagree (QA-0928-199).
//
//   node site/scripts/sync-seat-prices.mjs      (run from anywhere in the repo)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const config = join(here, '..', '..', 'src', 'config');
const newest = readdirSync(config).filter((f) => /^pricing-.*\.json$/.test(f)).sort().pop();
const sheet = JSON.parse(readFileSync(join(config, newest), 'utf8'));

const pick = (plan) => ({
  price_monthly: sheet.plans[plan].price_monthly,
  price_monthly_annual_billing: sheet.plans[plan].price_monthly_annual_billing,
});
const out = `// GENERATED by site/scripts/sync-seat-prices.mjs from src/config/${newest} — do not edit.
// Team seat list prices (USD per seat per month). seatPrices.test.js pins this to the sheet.
export const SEAT_PRICES = ${JSON.stringify({ sheet: newest, team_premium: pick('team_premium'), team_standard: pick('team_standard') }, null, 2).replace(/"([a-z_]+)":/g, '$1:').replace(/"/g, "'")} as const;
`;
const target = join(here, '..', 'src', 'lib', 'audit', 'seatPrices.ts');
writeFileSync(target, out);
console.log(`wrote ${target} from ${newest}`);
